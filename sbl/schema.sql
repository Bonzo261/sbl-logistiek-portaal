CREATE TABLE IF NOT EXISTS route (
  id INTEGER PRIMARY KEY, nummer INTEGER UNIQUE NOT NULL, naam TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS stembureau (
  id INTEGER PRIMARY KEY, nummer INTEGER UNIQUE NOT NULL, naam TEXT NOT NULL DEFAULT '',
  adres TEXT NOT NULL DEFAULT '', telefoon TEXT NOT NULL DEFAULT '',
  route_id INTEGER REFERENCES route(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS bericht (
  id INTEGER PRIMARY KEY, stembureau_id INTEGER REFERENCES stembureau(id) ON DELETE SET NULL,
  tekst TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'nieuw',
  route_id INTEGER REFERENCES route(id) ON DELETE SET NULL,
  ontvangen TEXT NOT NULL, onderweg_op TEXT, klaar_op TEXT
);
CREATE TABLE IF NOT EXISTS gebruiker (
  id INTEGER PRIMARY KEY, naam TEXT UNIQUE NOT NULL, hash TEXT NOT NULL,
  rol TEXT NOT NULL CHECK (rol IN ('beheerder','coordinator','chauffeur')),
  route_id INTEGER REFERENCES route(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS instelling (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS audit (
  id INTEGER PRIMARY KEY, tijd TEXT NOT NULL, gebruiker TEXT, actie TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS login_poging (
  id INTEGER PRIMARY KEY, tijd REAL NOT NULL, sleutel TEXT NOT NULL
);
